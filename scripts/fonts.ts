import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as fontkit from "fontkit";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cacheFile = resolve(root, ".cache/inter-500.ttf");
const target = resolve(root, "src/generated/label.ts");

const WEIGHT = 500;
const FONT_SIZE = 100;
const DECIMALS = 2;
const LABELS = {
  "built-on": "Built on Stellar",
  "powered-by": "Powered by Stellar",
} as const;

// A plain User-Agent makes Google return .ttf URLs instead of woff2.
const USER_AGENT = "community-stellar-badge";

async function loadFont(): Promise<Buffer> {
  if (existsSync(cacheFile)) return readFileSync(cacheFile);

  const cssUrl = `https://fonts.googleapis.com/css2?family=Inter:wght@${String(WEIGHT)}`;
  const css = await (await fetch(cssUrl, { headers: { "User-Agent": USER_AGENT } })).text();
  const fontUrl = /url\((https:[^)]+\.ttf)\)/.exec(css)?.[1];
  if (!fontUrl) throw new Error("no .ttf url in google fonts css");

  const response = await fetch(fontUrl);
  if (!response.ok) throw new Error(`font download failed: ${String(response.status)}`);
  const data = Buffer.from(await response.arrayBuffer());

  mkdirSync(dirname(cacheFile), { recursive: true });
  writeFileSync(cacheFile, data);
  return data;
}

const loaded = fontkit.create(await loadFont());
if (!("layout" in loaded)) throw new Error("expected a single font, got a collection");
const font = loaded;

const scale = FONT_SIZE / font.unitsPerEm;

function round(value: number): string {
  return String(Number(value.toFixed(DECIMALS)));
}

// fontkit shapes the text, which applies Inter's kerning from the GPOS table.
function layout(text: string): { d: string; width: number } {
  const run = font.layout(text);
  let x = 0;
  let d = "";
  run.glyphs.forEach((glyph, i) => {
    const position = run.positions[i];
    if (!position) throw new Error(`no position for glyph ${String(i)}`);
    const path = glyph.path.transform(
      scale,
      0,
      0,
      -scale,
      x + position.xOffset * scale,
      -position.yOffset * scale,
    );
    d += path.toSVG().replace(/-?\d+(?:\.\d+)?/g, (n) => round(Number(n)));
    x += position.xAdvance * scale;
  });
  return { d, width: Number(round(x)) };
}

const labels = Object.fromEntries(
  Object.entries(LABELS).map(([key, text]) => [key, { text, ...layout(text) }]),
);

const output = `// Generated by scripts/fonts.ts from Inter ${String(WEIGHT)}. Do not edit.
// Paths are drawn at fontSize ${String(FONT_SIZE)} with the baseline at y=0.
export const label = {
  fontSize: ${String(FONT_SIZE)},
  ascender: ${round(font.ascent * scale)},
  descender: ${round(font.descent * scale)},
  labels: ${JSON.stringify(labels, null, 2).replaceAll("\n", "\n  ")},
} as const;
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, output);
