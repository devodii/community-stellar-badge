import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "brand/logo/stellar.svg");
const target = resolve(root, "src/generated/logo.ts");

const svg = readFileSync(source, "utf8");

const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
if (!viewBox) throw new Error("logo svg has no viewBox");

const [minX, minY, width, height] = viewBox.split(/\s+/).map(Number);
if (minX !== 0 || minY !== 0 || !width || !height) {
  throw new Error(`unsupported viewBox: ${viewBox}`);
}

const paths = [...svg.matchAll(/<path\b[^>]*>/g)].map(([tag]) => {
  const d = /\sd="([^"]+)"/.exec(tag)?.[1];
  const fill = /\sfill="([^"]+)"/.exec(tag)?.[1];
  if (!d || !fill) throw new Error(`path is missing d or fill: ${tag}`);
  return { d, fill };
});
if (paths.length === 0) throw new Error("logo svg has no paths");

const output = `// Generated by scripts/logo.ts from brand/logo/stellar.svg. Do not edit.
export const logo = {
  viewBox: ${JSON.stringify(viewBox)},
  width: ${String(width)},
  height: ${String(height)},
  paths: ${JSON.stringify(paths, null, 2).replaceAll("\n", "\n  ")},
} as const;
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, output);
